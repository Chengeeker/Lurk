fun emojiUrl(text: String, name: String = "", cdn: String = ""): String {
    if (cdn.isNotEmpty()) return cdn.replaceFirst("http://", "https://")
    fun clean(value: String) = value.trim().removePrefix("#(").removeSuffix(")").removePrefix("[").removeSuffix("]")
    val id = emojiIds[clean(name)] ?: Regex("\\d+").find(text)?.value?.toIntOrNull() ?: emojiIds[clean(text)] ?: emojiIds[clean(text).lowercase()] ?: 1
    return "https://tb2.bdstatic.com/tb/editor/images/client/image_emoticon$id.png"
}

fun isEmoji(value: String): Boolean = value.contains("emoticon", true) || value.trim().removePrefix("#(").removeSuffix(")").removePrefix("[").removeSuffix("]").let { it in emojiIds || it.lowercase() in emojiIds }

